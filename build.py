#!/usr/bin/env python3
"""Bundle the site into one self-contained file at dist/page.html.

The site itself needs no build step — index.html, style.css and app.js are
served as they are. This is only for when you want a single file to hand
someone, email, or drop into a host that takes one document.

    python3 build.py

The CSS and JS are inlined; the webfont <link>s stay external (nothing else
reaches the network). Everything else about the page is untouched.

The checks at the bottom are the point: a previous hand-made dist/page.html
had lost its doctype and <meta charset>, so it rendered in quirks mode as
windows-1252 and showed "Â·" in the footer. The build now refuses to write a
file with that kind of damage instead of emitting it quietly.
"""

import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(HERE, "dist")
OUT = os.path.join(OUT_DIR, "page.html")

BANNER = ("<!-- Built by build.py from index.html + style.css + app.js.\n"
          "     Do not edit this file; edit the sources and run the build. -->\n")


def read(name):
    with io.open(os.path.join(HERE, name), encoding="utf-8") as fh:
        return fh.read()


def main():
    html = read("index.html")
    css = read("style.css")
    js = read("app.js")

    # A closing tag inside the inlined text would end the block early. Neither
    # file contains one today, but the escape is free and both forms mean the
    # same thing to the CSS and JS parsers.
    css = css.replace("</style", "<\\/style")
    js = js.replace("</script", "<\\/script")

    link = '<link rel="stylesheet" href="style.css">'
    script = '<script src="app.js"></script>'

    if html.count(link) != 1:
        sys.exit("build: expected exactly one %s in index.html" % link)
    if html.count(script) != 1:
        sys.exit("build: expected exactly one %s in index.html" % script)

    html = html.replace(link, "<style>\n" + css.strip() + "\n</style>", 1)
    html = html.replace(script, "<script>\n" + js.strip() + "\n</script>", 1)
    html = html.replace("<!doctype html>", "<!doctype html>\n" + BANNER.rstrip(), 1)

    # --- refuse to ship a broken document ------------------------------------
    problems = []
    if not html.lower().lstrip().startswith("<!doctype html>"):
        problems.append("no doctype (the page would render in quirks mode)")
    for needle, why in (
        ('<meta charset="utf-8">', "no charset (non-ASCII renders as mojibake)"),
        ('name="viewport"', "no viewport meta (mobile renders zoomed out)"),
        ("<html", "no <html> element"),
        ("<head>", "no <head> element"),
        ("<body>", "no <body> element"),
        ("</html>", "unclosed document"),
    ):
        if needle not in html:
            problems.append(why)
    if 'href="style.css"' in html or 'src="app.js"' in html:
        problems.append("a source file is still linked instead of inlined")
    if re.search(r'(?<!:)//[^\s"\']*\.css', html):
        problems.append("stylesheet link survived inlining")

    if problems:
        sys.exit("build: refusing to write a broken bundle:\n  - " +
                 "\n  - ".join(problems))

    if not os.path.isdir(OUT_DIR):
        os.makedirs(OUT_DIR)
    with io.open(OUT, "w", encoding="utf-8") as fh:
        fh.write(html)

    print("built %s  (%.1f KB, one file, no local dependencies)"
          % (os.path.relpath(OUT, HERE), len(html.encode("utf-8")) / 1024.0))


if __name__ == "__main__":
    main()
